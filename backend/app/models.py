from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

class SourceCitation(BaseModel):
    source: str = Field(..., description="Original PDF file name")
    page: int = Field(..., description="1-indexed page number in the source PDF")
    snippet: str = Field(..., description="Relevant text excerpt from this chunk")
    score: Optional[float] = Field(None, description="Similarity score or distance")

class DocumentMetadata(BaseModel):
    filename: str
    pages: int
    chunks: int
    size_bytes: int
    uploaded_at: str
    content_hash: Optional[str] = None

class ChatMessage(BaseModel):
    role: str = Field(..., description="'user' or 'assistant'")
    content: str = Field(..., description="Message text")
    sources: Optional[List[SourceCitation]] = Field(default=None, description="Citations if generated by assistant")
    timestamp: Optional[str] = Field(default=None, description="ISO timestamp")
    feedback: Optional[str] = Field(default=None, description="'helpful' or 'unhelpful'")

class ChatRequest(BaseModel):
    question: str = Field(..., min_length=1, description="Question to ask against the PDFs")
    session_id: str = Field(default="default", description="Conversation session identifier")
    top_k: Optional[int] = Field(default=4, ge=1, le=10, description="Number of context chunks to retrieve")

class ChatResponse(BaseModel):
    answer: str = Field(..., description="LLM generated answer based on retrieved context")
    sources: List[SourceCitation] = Field(default_factory=list, description="Source PDF names and page numbers")
    session_id: str = Field(..., description="Session identifier")

class UploadResponse(BaseModel):
    message: str
    files_processed: List[str]
    total_pages: int
    total_chunks: int
    documents: List[DocumentMetadata]

class StatusResponse(BaseModel):
    status: str
    has_google_key: bool
    has_groq_key: bool
    total_chunks: int
    indexed_files: List[str]
    documents: List[DocumentMetadata]
    groq_model: str
    embedding_model: str

class ClearResponse(BaseModel):
    message: str
    session_id: str

class SummarizeRequest(BaseModel):
    filename: Optional[str] = Field(default=None, description="Optional specific filename to summarize; if None summarizes all")
    format_type: str = Field(default="executive", description="'executive', 'bullet_points', or 'detailed'")

class SummarizeResponse(BaseModel):
    summary: str
    key_takeaways: List[str]
    sources: List[SourceCitation]

class CompareRequest(BaseModel):
    filenames: Optional[List[str]] = Field(default=None, description="List of filenames to compare; defaults to all uploaded")

class CompareResponse(BaseModel):
    comparison: str
    similarities: List[str]
    differences: List[str]
    sources: List[SourceCitation]

class StudyModeRequest(BaseModel):
    topic: Optional[str] = Field(default=None, description="Optional focus topic")
    num_questions: int = Field(default=5, ge=1, le=10)

class Flashcard(BaseModel):
    front: str
    back: str
    source_hint: str

class QuizQuestion(BaseModel):
    question: str
    options: List[str]
    correct_answer: str
    explanation: str
    source: str

class StudyModeResponse(BaseModel):
    study_notes: str
    flashcards: List[Flashcard]
    quiz: List[QuizQuestion]

class FeedbackRequest(BaseModel):
    session_id: str
    message_index: int
    feedback: str = Field(..., pattern="^(helpful|unhelpful)$")
    comment: Optional[str] = None

class FeedbackResponse(BaseModel):
    status: str
    message: str
